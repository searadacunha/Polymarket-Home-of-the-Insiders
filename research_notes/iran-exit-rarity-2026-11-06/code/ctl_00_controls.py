"""Positive controls on synthetic populations, run before the freeze. No real data is read.

python3 -I code/ctl_00_controls.py   -> controles/controles_positifs.md, registry lines marked synthetic

Generator: wallet degrees 1 + geometric(0.5), capped at 30; each edge goes to a fresh recipient with
probability 0.9, otherwise to a shared pool of n/5 recipients, half of them SERVICE. Plants add g
wallets that all hold r new CUSTOMER recipients. Traps: a SERVICE hub held by 30 wallets, and five
wallets of degree 30 drawing half their edges from the pool.
"""
import random
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ALPHA, ETUDE, POWER_MIN, permutation_test, power, verdict  # noqa: E402
from registre import enregistrer  # noqa: E402


def synth(n, seed, plant=(0, 0), service_hub=False, heavy=False):
    rng = random.Random(seed)
    pool = [f"pool{i}" for i in range(max(2, n // 5))]
    cls = {r: ("SERVICE" if i % 2 else "CUSTOMER") for i, r in enumerate(pool)}
    D, fresh = {}, 0
    for i in range(n):
        d = 1
        while rng.random() < 0.5 and d < 30:
            d += 1
        if heavy and i < 5:
            d = 30
        rs = set()
        p_fresh = 0.5 if heavy and i < 5 else 0.9  # heavy wallets draw half their edges from the pool
        while len(rs) < d:
            if rng.random() < p_fresh:
                rs.add(f"fresh{fresh}"); fresh += 1
            else:
                rs.add(rng.choice(pool))
        D[f"w{i}"] = rs
    g, r = plant
    for w in rng.sample(sorted(D), g) if g else []:
        D[w] |= {f"plant{j}" for j in range(r)}
    for j in range(r):
        cls[f"plant{j}"] = "CUSTOMER"
    if service_hub:
        cls["hub"] = "SERVICE"
        for w in rng.sample(sorted(D), min(30, n)):
            D[w].add("hub")
    return D, cls


def main():
    lines, t0 = [], time.time()
    lines.append("# Positive controls, synthetic populations only\n")
    lines.append("Generated by `code/ctl_00_controls.py` before the freeze. Each row runs `permutation_test` "
                 f"(the analysis function, {2000} draws) on a synthetic population. Detection means p_M <= {ALPHA}.\n")
    lines.append("| Scenario | n wallets | seeds | detected | p_M per seed |")
    lines.append("|---|---|---|---|---|")
    scen = [("null", 0, 0), ("weak plant: 2 wallets x 2 recipients", 2, 2), ("medium plant: 4 x 2", 4, 2),
            ("strong plant: 9 x 3", 9, 3)]
    found = {}
    for n in (20, 60, 120):
        for name, g, r in scen:
            ps = []
            for s in range(5):
                D, cls = synth(n, 1000 * n + s, plant=(g, r))
                ps.append(permutation_test(D, cls, seed=s)["p_M"])
            det = sum(p <= ALPHA for p in ps)
            found[(n, name)] = det
            lines.append(f"| {name} | {n} | 5 | {det}/5 | {', '.join(f'{p:.4f}' for p in ps)} |")
            enregistrer(str(ETUDE), test=f"CTL_{name.split(':')[0].replace(' ', '_')}_n{n}", declare=False, n=n,
                        agent="ctl_00_controls", donnees="synthetiques", n_comparaisons=5,
                        params={"g": g, "r": r}, stat=det)
    # null calibration: share of p_M <= alpha over 40 null populations
    nulls = [permutation_test(*synth(60, 50_000 + s), seed=s)["p_M"] for s in range(40)]
    fp = sum(p <= ALPHA for p in nulls)
    lines.append(f"\nNull calibration: {fp} of 40 null populations of 60 wallets reach p_M <= {ALPHA}"
                 f" (smallest p {min(nulls):.4f}).\n")
    enregistrer(str(ETUDE), test="CTL_null_calibration", declare=False, n=40, agent="ctl_00_controls",
                donnees="synthetiques", stat=fp)
    # traps
    traps = []
    for s in range(5):
        D, cls = synth(60, 70_000 + s, service_hub=True)
        traps.append(("SERVICE hub held by 30 wallets", permutation_test(D, cls, seed=s)))
        D, cls = synth(60, 80_000 + s, heavy=True)
        traps.append(("five wallets of degree 30 on the pool", permutation_test(D, cls, seed=s)))
    lines.append("| Trap | seeds | p_M <= alpha | observed M per seed |")
    lines.append("|---|---|---|---|")
    for name in ("SERVICE hub held by 30 wallets", "five wallets of degree 30 on the pool"):
        rs = [r for k, r in traps if k == name]
        lines.append(f"| {name} | 5 | {sum(r['p_M'] <= ALPHA for r in rs)}/5 | {', '.join(str(r['M']) for r in rs)} |")
        enregistrer(str(ETUDE), test=f"CTL_trap_{name.split()[0]}", declare=False, n=5, agent="ctl_00_controls",
                    donnees="synthetiques", stat=sum(r["p_M"] <= ALPHA for r in rs))
    # power eligibility: the benchmark plant must be found in the population's own structure
    small, large = synth(20, 5151), synth(120, 5252)
    p_small, p_large = power(*small, "small"), power(*large, "large")
    lines.append(f"\nPower rule: the planted benchmark (9 wallets x 3 recipients) is found in {p_small} of 3 seeds on a null "
                 f"population of 20 wallets (not eligible) and {p_large} of 3 on one of 120 (eligible, at least {POWER_MIN}).\n")
    enregistrer(str(ETUDE), test="CTL_power_rule", declare=False, n=2, agent="ctl_00_controls", donnees="synthetiques",
                stat=int(p_small < POWER_MIN <= p_large))

    # verdict end to end, comparators carry their power
    def pops(k, plant_every=None, size=80, base=90_000):
        out = []
        for i in range(k):
            pl = (9, 3) if plant_every and i % plant_every == 0 else (0, 0)
            D, c = synth(size, base + i, plant=pl)
            out.append({**permutation_test(D, c, seed=i), "power": power(D, c, f"pop{base + i}")})
        return out
    strong_ref = permutation_test(*synth(78, 4242, plant=(9, 3)), seed=1)
    null_ref = permutation_test(*synth(78, 4343), seed=1)
    null12 = pops(12)
    cases = [("strong reference, 12 null comparators of 80", strong_ref, null12, "RARE"),
             ("strong reference, 12 comparators of 80, every 2nd planted", strong_ref, pops(12, plant_every=2), "COMMON"),
             ("null reference, 12 null comparators of 80", null_ref, null12, "REFERENCE_NOT_DISTINCT"),
             ("strong reference, 6 comparators of 80", strong_ref, null12[:6], "UNDETERMINED"),
             ("bias trap: strong reference, 6 planted comparators of 15 and 6 null of 80", strong_ref,
              pops(6, plant_every=1, size=15, base=95_000) + null12[:6], "UNDETERMINED")]
    lines.append("| Verdict case | expected | obtained |")
    lines.append("|---|---|---|")
    ok = True
    for name, ref, comp, exp in cases:
        v = verdict(ref, comp)
        ok &= v["verdict"] == exp
        lines.append(f"| {name} | {exp} | {v['verdict']} (n {v['n_comparators']}, rate {v['rate']}, "
                     f"without power {v['comparators_without_power']}) |")
        enregistrer(str(ETUDE), test=f"CTL_verdict_{exp}", declare=False, n=len(comp), agent="ctl_00_controls",
                    donnees="synthetiques", stat=int(v["verdict"] == exp))
    gate = (fp <= 2 and all(found[(n, "strong plant: 9 x 3")] == 5 for n in (60, 120)) and ok
            and p_small < POWER_MIN <= p_large
            and all(r["p_M"] > ALPHA for k, r in traps if k.startswith("SERVICE")))
    lines.append(f"\nGate: null silent (at most 2 of 40), strong plant always found at 60 and 120 wallets, power rule "
                 f"separates 20 from 120 wallets, SERVICE hub never flagged, verdicts as expected: "
                 f"**{'PASS' if gate else 'FAIL'}**. Run time {time.time() - t0:.0f} s.")
    lines.append("\nKnown limit, kept in the table above: at 20 wallets the strong plant is not found, because three "
                 "recipients held by 9 of 20 wallets overlap by chance under a degree-preserving null. The power rule "
                 "keeps such populations out of the rate instead of counting them as populations without excess.")
    (ETUDE / "controles" / "controles_positifs.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    if not gate:
        raise SystemExit("controls failed")


if __name__ == "__main__":
    main()
